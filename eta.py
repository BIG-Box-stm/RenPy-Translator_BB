# -*- coding: utf-8 -*-
"""
Примерное время до завершения перевода: «Времени до завершения: ММ:СС»
(или ЧЧ:ММ:СС, если осталось больше часа).

Прогноз строится по средней скорости за всё время работы: сколько строк
уже переведено (done) за сколько секунд (elapsed) — отсюда время на одну
строку, умножаем на число оставшихся. Средняя за всё время, а не за
последние секунды, выбрана сознательно: при параллельном переводе
(несколько потоков Translate Gemma, пачки у Google/DeepL) мгновенная
скорость сильно скачет от строки к строке, а общая средняя даёт
спокойное, не дёргающееся число — для «примерного» времени этого
достаточно.

Пока накоплено слишком мало данных (первые пару секунд/строк, когда
модель ещё "разогревается" или идёт первый сетевой запрос), честной
оценки нет — показываем «считаю...», а не случайное число.

Отдельным модулем сделано ради того, чтобы формулу можно было проверять
без окна Tkinter.
"""

LABEL = "Времени до завершения: "
MIN_ITEMS = 3
MIN_SECONDS = 3.0


def format_duration(seconds):
    """ММ:СС, либо ЧЧ:ММ:СС, если часов больше нуля."""
    seconds = max(0, int(round(seconds)))
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    if hours:
        return "{0:02d}:{1:02d}:{2:02d}".format(hours, minutes, secs)
    return "{0:02d}:{1:02d}".format(minutes, secs)


def eta_text(done, total, elapsed):
    """Строка для отображения в окне. Пустая, если считать нечего
    (нет общего числа строк) или всё уже сделано."""
    if total <= 0 or done >= total:
        return ""
    if done < MIN_ITEMS or elapsed < MIN_SECONDS:
        return LABEL + "считаю..."
    remaining = (total - done) * (elapsed / done)
    return LABEL + format_duration(remaining)
